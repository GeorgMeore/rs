/*
The encoder receives message bytes (m_1, ..., m_n), interprets them
as GF(256) numbers and constructs the code polynomial:

	c(x) = m(x) - (m(x) mod g(x))

where

	m(x) = x^k * (m_1 * x^n-1 + ... + m_n).
	g(x) = (x - α^0)...(x - α^k-1)

and α is the primitive element of the field.

This polynomial has two important properties:

 1. c(x) is divisible by g(x) by definition, therefore
    c(α^j) = 0 for all j = 0..k-1

 2. deg(m(x) mod g(x)) < deg(g) = deg(x^k), therefore
    the "top" n coefficients of c(x) are (m_1, ..., m_n), i.e.
    the encoder simply appends k redundancy bytes to the message

Coefficients of c(x) are the codeword to be transmitted.
*/

type RSerror string

const (
	Eparam RSerror = "invalid parameters"
	Eunrec RSerror = "recovery failed"
)

func (e RSerror) Error() string {
	return string(e)
}

// returns k redundant bytes to be appended to the data
func encode(data []byte, k int) ([]byte, error) {
	if k <= 0 || k > MaxEcc || k+len(data) > 255 || len(data) == 0 {
		return nil, Eparam
	}
	r := pmodk(data, gtab[k], k)
	return r, nil
}

/*
Compute the formal derivative of a little-endian polynomial.

fddx(c0 + c1*x + ... +cn*x^n) = c1 + (c2 + c2)x + ... + (cn + ... + cn)x^(n-1)

If {c0,...,cn} are elements of GF(2^n), addition is a simple xor, therefore
(ci + ... + ci) will be equal to 0 if i is even and ci if i is odd.
*/
func fddx(p Poly) Poly {
	d := make(Poly, len(p)-1)
	for i := 0; i < len(d); i += 2 {
		d[i] = p[i+1]
	}
	return d
}

/*
The decoder receives a polynomial c'(x) = c(x) + e(x), where c is the transmitted
codeword (c(α^j) = 0), and e is the error introduced during transmission.

	S_j = c'(α^j) = e(α^j) = ∑[i]e_i*(α^j)^i = ∑[i]e_i*(α^i)^j.

Let {i1, ..., iv} be all positions where e_i != 0, Y_k = e_ik, X_k = (α^ik), then

	S_j = ∑[k=1..v]Y_k*X_k^j.

We define the error locator polynomial:

	L(x) = ∏[i=1..v](1 - X_i*x) = 1 + L_1*x + ... + L_v*x^v
	L(X_k^-1) = 0.

We can multiply both sides of the last equation by Y_k*X_k^(j+v),

	Y_k*X_k^(j+v)*L(X_k^-1) = 0
	Y_k*X_k^(j+v)*(1 + L_1*X_k^-1 + ... + L_v*X_k^-v) = 0
	Y_k*X_k^(j+v) + L_1*Y_k*X_k^(j+v-1) + ... + L_v*Y_k*X_k^j = 0

and then sum over k,

	(∑Y_k*X_k^(j + v)) + L_1*(∑Y_k*X_k^(j + v - 1)) + ... + L_v*(∑Y_k*X_k^j) = 0
	S_j+v + L_1*S_j+v-1 + ... + L_v*S_j = 0.

So we know that coefficients of L(x) give the linear recurrence formula for syndromes.
Berlekamp-Massey algorithm comes to help here, it can find the minimal recurrence that
satisfies a series of values. But how can we be sure that its output will be L?

Suppose that Berlekamp-Massey gives us back G(x) = 1 + G_1*x + ... +G_m*x^m, such that

	S_j+m + G_1*S_j+m-1 + ... + G_m*S_j = 0.

It's obvious that G cannot be longer than L, since the algorithm produces the minimal
recurrence. But can it be shorter or of the same length?

By expanding S terms we get (for any i >= m):

	∑[j=0..m]G_j*S_i-j =
	∑[j=0..m]G_j*(∑[k=1..v]Y_k*X_k^i-j) =
	∑[j=0..m]∑[k=1..v](G_j*Y_k*X_k^i-j) =
	∑[k=1..v]∑[j=0..m](G_j*Y_k*X_k^i-j) =
	∑[k=1..v](Y_k*X_k^i*∑[j=0..m]G_j*X_k^-j) =
	∑[k=1..v](Y_k*X_k^i*G(X_k^-1)) = 0

If we have enough syndromes, we can range i over {v, ..., 2v-1} and get the following
system of equations:

	/ 1        1        ... 1     \ / X_1^v*Y_1*G(X_1^-1) \
	|             ...             | |         ...         | = 0
	\ X_1^v-1 X_2^v-1 ... X_v^v-1 / \ X_v^v*Y_v*G(X_v^-1) /

The equation matrix is a Vandermonde matrix (which is invertible since X_k are distinct),
so given that Y_k != 0 it must be that G(X_k^-1) = 0. This means that G has at least v roots
and therefore deg(G) >= v.

Now we know that deg(G) = v = deg(L), G_0 = L_0 and both polynomials have the same v
non-zero roots, that's only possible if G = L.

Therefore given at least 2*v syndromes, the Berlekamp-Massey will correctly
find the error locator polynomial of v errors.
*/

func zero(s []Gf256) bool {
	for _, v := range s {
		if v != 0 {
			return false
		}
	}
	return true
}

/*
Apart from errors we also want to be able to efficiently correct erasures,
i.e. errors at known locations. Suppose in total v symbols were corrupted,
n erasures in known positions e1,..,en and m errors in u1,..,um.

First we compute the locator polynomial for erasures:

	G(x) = ∏[i=e1,..,en](1 - X_i*x).

Then we compute T(x) = G(x) * S(x)

	T_j = ∑[i]G_i * S_j-i
	    = ∑[i]G_i*(∑[k=1..v]Y_k*X_k^j-i)
	    = ∑[k=1..v]Y_k*X_k^j*(∑[i]G_i*X_k^-i)

If deg(G) <= j <= deg(S), i ranges over 0..deg(G) and we can simplify further

	T_j = ∑[k=1..v]Y_k*X_k^j*G(X_k^-1)

And since G(X_i^-1) = 0 for all i = e1,..,en

	T_j = ∑[l=u1,u2..]Y'_l*X_l^j, where Y'_l = Y_l*G(X_l^-1)

This way we get deg(S)-deg(G)+1 updated syndromes (aka Forney syndromes)
that isolate errors at unknown locations, on which we can run Berlekamp-Massey.
*/

func locate(bad []int, S []Gf256, n int) (Poly, error) {
	L := Poly{1}
	for _, v := range bad {
		if v >= n {
			return nil, Eparam
		}
		L = pmul(L, Poly{1, pow[n-1-v]})
	}
	T := pmul(L, S)[len(bad):len(S)]
	if !zero(T) {
		l := slr(T)
		if len(l) < 2 || len(l)-1 > len(T)/2 {
			return nil, Eunrec
		}
		L = pmul(L, l)
	}
	return L, nil
}

func fix(code, L, S []Gf256) (int, error) {
	r := roots(L)
	if len(r) != len(L)-1 {
		return 0, Eunrec
	}
	O := pmul(L, S)[:len(S)]
	Ld := fddx(L)
	for n, v := range r {
		u := inv(v)
		i := int(log[u])
		if i >= len(code) {
			return n, Eunrec
		}
		j := len(code) - 1 - i
		e := mul(u, div(peval(O, v), peval(Ld, v)))
		code[j] = sub(code[j], e)
	}
	return len(r), nil
}

func syndromes(code []byte, k int) []Gf256 {
	S := make([]Gf256, k)
	p := len(code) - 1
	for i := range S {
		S[i] = code[p]
	}
	m := Gf256(pow[1])
	for i := 1; i <= p; i++ {
		v := code[p-i]
		for j := range S {
			S[j] = add(S[j], v)
			v = mul(v, m)
		}
		m = mul(m, pow[1])
	}
	return S
}

// corrects code errors in place and returns the number of corrected symbols
func decode(code []byte, k int, bad ...int) (int, error) {
	if k <= 0 || k > MaxEcc || len(code) > 255 || len(code) <= k || len(bad) > k {
		return 0, Eparam
	}
	S := syndromes(code, k)
	if zero(S) {
		return 0, nil
	}
	L, err := locate(bad, S, len(code))
	if err != nil {
		return 0, err
	}
	return fix(code, L, S)
}

func main() {
	data := []byte("Hello, world")
	fmt.Printf("data: %v (%v)\n", data, string(data))
	ecc := 3
	synd, err := encode(data, ecc)
	if err != nil {
		panic(err)
	}
	code := append(data, synd...)
	fmt.Println("send:", code)
	code[3] ^= 123
	code[5] ^= 123
	fmt.Println("recv:", code)
	n, err := decode(code, ecc, 5)
	if err != nil {
		panic(err)
	}
	fmt.Printf("done: %v (%v), %v errors\n", code[:len(code)-ecc], string(code[:len(code)-ecc]), n)
}
