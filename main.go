func encode(data []byte, k int) []byte {
	if k <= 0 || k > MaxEcc || k+len(data) > 255 || len(data) == 0 {
		return nil
	}
	p := make(Poly, len(data)+k)
	for i, v := range data {
		p[len(p)-1-i] = v
	}
	r := pmod(p, gtab[k])
	for i, v := range r {
		p[i] = v
	}
	return reverse(p)
}

/*
The decoder receives a polynomial c'(x) = c(x) + e(x), where c is the transmitted
codeword (c(α^j) = 0), and e is the error introduced during transmission.

	S_j = c'(α^j) = e(α^j) = ∑[i]e_i*(α^j)^i = ∑[i]e_i*(α^i)^j.

Let {i1, ..., iv} be all positions where e_i != 0, Y_k = e_ik, X_k = (α^ik), then

	S_j = ∑[k=1..v]Y_k*X_k^j.

We define the error locator polynomial:

	L(x) = (1 - X_1*x)*...*(1 - X_v*x) = 1 + L_1*x + ... + L_v*x^v
	L(X_k^-1) = 0.

We can multiply both sides of the last equation by Y_k*X_k^(j+v),

	Y_k*X_k^(j+v)*L(X_k^-1) = 0
	Y_k*X_k^(j+v)*(1 + L_1*X_k^-1 + ... + L_v*X_k^-v) = 0
	Y_k*X_k^(j+v) + L_1*Y_k*X_k^(j+v-1) + ... + L_v*Y_k*X_k^j = 0

and then sum over k,

	(∑Y_k*X_k^(j + v)) + L_1*(∑Y_k*X_k^(j + v - 1)) + ... + L_v*(∑Y_k*X_k^j) = 0
	S_j+v + L_1*S_j+v-1 + ... + L_v*S_j = 0.

So we know that coefficients of L(x) give the linear recurrence formula for syndromes.
Berlekamp-Massey algorithm comes to help here, it can find the minimal recurrence that
satisfies a series of values. But how can we be sure that its output will be L?

Suppose that Berlekamp-Massey gives us back G(x) = 1 + G_1*x + ... +G_m*x^m, such that

	S_j+m + G_1*S_j+m-1 + ... + G_m*S_j = 0.

It's obvious that G cannot be longer than L, since the algorithm produces the minimal
recurrence. But can it be shorter or of the same length?

By expanding S terms we get (for any i >= m):

	∑[j=0..m]G_j*S_i-j =
	∑[j=0..m]G_j*(∑[k=1..v]Y_k*X_k^i-j) =
	∑[j=0..m]∑[k=1..v](G_j*Y_k*X_k^i-j) =
	∑[k=1..v]∑[j=0..m](G_j*Y_k*X_k^i-j) =
	∑[k=1..v](Y_k*X_k^i*∑[j=0..m]G_j*X_k^-j) =
	∑[k=1..v](Y_k*X_k^i*G(X_k^-1)) = 0

If we have enough syndromes, we can range i over {v, ..., 2v-1} and get the following
system of equations:

	/ 1        1        ... 1     \ / X_1^v*Y_1*G(X_1^-1) \
	|             ...             | |         ...         | = 0
	\ X_1^v-1 X_2^v-1 ... X_v^v-1 / \ X_v^v*Y_v*G(X_v^-1) /

The equation matrix is a Vandermonde matrix (which is invertible since X_k are distinct),
so given that Y_k != 0 it must be that G(X_k^-1) = 0. This means that G has at least v roots
and therefore deg(G) >= v.

Now we know that deg(G) = v = deg(L), G_0 = L_0 and both polynomials have the same v
non-zero roots, that's only possible if G = L.

Therefore given at least 2*v syndromes, the Berlekamp-Massey will correctly
find the error locator polynomial of v errors.
*/

func syndromes(code []Gf256, k int) []Gf256 {
	s := make([]Gf256, k)
	c := make([]Gf256, len(code))
	copy(c, code)
	c = reverse(c)
	for i := 0; i < k; i++ {
		v := Gf256(0)
		for j := range c {
			v = add(v, c[j])
			c[j] = mul(c[j], pow[j])
		}
		s[i] = v
	}
	return s
}

func zero(s []Gf256) bool {
	for _, v := range s {
		if v != 0 {
			return false
		}
	}
	return true
}

func erasures(lost []byte, n int) Poly {
	g := Poly{1}
	for _, v := range lost {
		if int(v) >= n {
			return nil
		}
		g = pmul(g, Poly{1, pow[n-1-int(v)]})
	}
	return g
}

